import { describe, expect, it } from "vitest";

import {
  FLAG_ON,
  USER,
  adjust,
  adjustmentSetup as setup,
  asUser,
  available,
  bookingId,
  completeBooking,
  newBooking,
  partnerId,
  run,
} from "@/lib/finance/finance-test-support";

/**
 * VI-F04-S13 (spec R8, R19, E8): the admin moves a settlement through its statuses, the bookings of an
 * approved settlement are locked, and an adjustment made afterwards is carried to the next settlement
 * without changing the approved one. The rentals are of six days at 75 (450.00 gross; 30 percent for
 * the partner). Every scenario runs in a transaction that is rolled back. Skipped when the local stack
 * is not running, like the RLS suite.
 */
const D = (month: number, day: number) => `2026-${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")} 10:00:00+00`;

/** A completed rental returned on `ret`, six days after its pickup. */
const rental = (n: number, partner: number, month: number, day = 7) => `
  ${newBooking(n, partner, D(month, day), "75", D(month, day - 6))}
  ${completeBooking(n)}`;

const generate = (partner: number, month: string) => `select public.generate_monthly_settlement('${partnerId(partner)}', date '${month}');`;

const settlementOf = (partner: number, month: string) =>
  `(select id from public.settlements where partner_id = '${partnerId(partner)}' and period_start = date '${month}')`;

/** Moves a settlement and reports `R|name|ok` or `R|name|<sqlstate>`. */
const move = (name: string, partner: number, month: string, to: string) => `
  do $$ begin
    perform public.move_settlement_status(${settlementOf(partner, month)}, '${to}');
    raise notice 'R|${name}|ok';
  exception when others then
    raise notice 'R|${name}|%', sqlstate;
  end $$;`;

/** Runs any statement and reports `R|name|ok` or `R|name|<sqlstate>`. */
const attempt = (name: string, statement: string) => `
  do $$ begin
    ${statement}
    raise notice 'R|${name}|ok';
  exception when others then
    raise notice 'R|${name}|%', sqlstate;
  end $$;`;

/** Reports `R|name|status|changed by admin|gross|partner|platform|refunds|adjustments|chargebacks|final`. */
const state = (name: string, partner: number, month: string) => `
  do $$ declare s record; begin
    select * into s from public.settlements where id = ${settlementOf(partner, month)};
    raise notice 'R|${name}|%|%|%|%|%|%|%|%|%', s.status,
      (s.status_changed_by is not distinct from ${USER("admin")}::uuid), s.gross_revenue, s.partner_share,
      s.platform_share, s.refunds, s.adjustments, s.chargebacks, s.final_amount;
  end $$;`;

const get = (rows: string[][], name: string) => {
  const row = rows.find((r) => r[0] === name);
  expect(row, name).toBeDefined();
  return row!.slice(1);
};

/** A settled January for a partner: one rental, a draft generated by the admin. */
const january = (partner: number) => `
  ${setup(partner)} ${rental(1, partner, 1)}
  ${asUser("admin")}
  ${generate(partner, "2026-01-01")}`;

describe.skipIf(!available)("moving a settlement (VI-F04-S13, spec R8, R19, E8)", () => {
  it("should walk the settlement from draft to paid and save who moved it and when (AC01)", () => {
    const rows = run(`
      ${january(1)}
      ${state("draft", 1, "2026-01-01")}
      ${move("m1", 1, "2026-01-01", "pending_approval")}
      ${state("pending", 1, "2026-01-01")}
      ${move("m2", 1, "2026-01-01", "approved")}
      ${state("approved", 1, "2026-01-01")}
      ${move("m3", 1, "2026-01-01", "paid")}
      ${state("paid", 1, "2026-01-01")}`);

    expect(["m1", "m2", "m3"].map((n) => get(rows, n))).toEqual([["ok"], ["ok"], ["ok"]]);
    expect(get(rows, "draft").slice(0, 2)).toEqual(["draft", "t"]);
    expect(get(rows, "pending").slice(0, 2)).toEqual(["pending_approval", "t"]);
    expect(get(rows, "approved").slice(0, 2)).toEqual(["approved", "t"]);
    expect(get(rows, "paid").slice(0, 2)).toEqual(["paid", "t"]);
  });

  it("should record the time of the move, later than the time it was generated (AC01)", () => {
    const rows = run(`
      ${january(2)}
      ${move("m", 2, "2026-01-01", "pending_approval")}
      do $$ declare s record; begin
        select * into s from public.settlements where id = ${settlementOf(2, "2026-01-01")};
        raise notice 'R|t|%', s.status_changed_at >= s.created_at;
      end $$;`);

    expect(get(rows, "t")).toEqual(["t"]);
  });

  it("should send a settlement that waits for approval back to draft", () => {
    const rows = run(`
      ${january(3)}
      ${move("a", 3, "2026-01-01", "pending_approval")}
      ${move("b", 3, "2026-01-01", "draft")}
      ${state("s", 3, "2026-01-01")}`);

    expect(get(rows, "b")).toEqual(["ok"]);
    expect(get(rows, "s")[0]).toBe("draft");
  });

  it.each([
    ["draft", "approved", []],
    ["draft", "paid", []],
    ["draft", "draft", []],
    ["pending_approval", "paid", ["pending_approval"]],
    ["approved", "pending_approval", ["pending_approval", "approved"]],
    ["approved", "draft", ["pending_approval", "approved"]],
    ["paid", "approved", ["pending_approval", "approved", "paid"]],
    ["paid", "draft", ["pending_approval", "approved", "paid"]],
  ])("should refuse the move from %s to %s with ST006 and keep the status (AC01)", (from, to, path) => {
    const rows = run(`
      ${january(4)}
      ${path.map((step, i) => move(`p${i}`, 4, "2026-01-01", step)).join("\n")}
      ${move("bad", 4, "2026-01-01", to)}
      ${state("s", 4, "2026-01-01")}`);

    expect(get(rows, "bad")).toEqual(["ST006"]);
    expect(get(rows, "s")[0]).toBe(from);
  });

  it.each([
    ["an operations manager", "operations_manager"],
    ["a technician", "technician"],
    ["a partner user", "partner_user"],
    ["nobody signed in", null],
  ])("should refuse %s with 42501 and keep the status (AC01)", (_name, role) => {
    const rows = run(`
      ${january(5)}
      ${asUser(role)}
      ${move("m", 5, "2026-01-01", "pending_approval")}
      ${asUser("admin")}
      ${state("s", 5, "2026-01-01")}`);

    expect(get(rows, "m")).toEqual(["42501"]);
    expect(get(rows, "s")[0]).toBe("draft");
  });

  it("should refuse an unknown settlement with P0002 and a missing value with 22023", () => {
    const rows = run(`
      ${asUser("admin")}
      ${attempt("unknown", "perform public.move_settlement_status('00000000-0000-0000-0000-00000000dead', 'pending_approval');")}
      ${attempt("nothing", "perform public.move_settlement_status(null, 'pending_approval');")}`);

    expect(get(rows, "unknown")).toEqual(["P0002"]);
    expect(get(rows, "nothing")).toEqual(["22023"]);
  });

  it("should refuse a change of the status outside the function, even to an admin (AC01)", () => {
    const rows = run(`
      ${january(6)}
      ${attempt("direct", `update public.settlements set status = 'paid' where id = ${settlementOf(6, "2026-01-01")};`)}
      ${attempt("who", `update public.settlements set status_changed_by = null where id = ${settlementOf(6, "2026-01-01")};`)}
      ${state("s", 6, "2026-01-01")}`);

    expect(get(rows, "direct")).toEqual(["55000"]);
    expect(get(rows, "who")).toEqual(["55000"]);
    expect(get(rows, "s")[0]).toBe("draft");
  });

  it("should refuse a change of the figures once the settlement is not a draft, and allow it on a draft", () => {
    const rows = run(`
      ${january(7)}
      ${attempt("draft", `update public.settlements set fees = 1 where id = ${settlementOf(7, "2026-01-01")};`)}
      ${move("m", 7, "2026-01-01", "pending_approval")}
      ${attempt("pending", `update public.settlements set fees = 2 where id = ${settlementOf(7, "2026-01-01")};`)}`);

    expect(get(rows, "draft")).toEqual(["ok"]);
    expect(get(rows, "pending")).toEqual(["55000"]);
  });
});

describe.skipIf(!available)("bookings of an approved settlement (VI-F04-S13, spec R19)", () => {
  const edit = (name: string, n: number, set: string) =>
    attempt(name, `${FLAG_ON.replace("select", "perform")} update public.bookings set ${set} where id = '${bookingId(n)}';`);

  it("should lock the booking once the settlement is approved, and when it is paid (AC02)", () => {
    const rows = run(`
      ${january(10)}
      ${move("a", 10, "2026-01-01", "pending_approval")}
      ${edit("pending", 1, "daily_rate = 80")}
      ${move("b", 10, "2026-01-01", "approved")}
      ${edit("rate", 1, "daily_rate = 90")}
      ${edit("status", 1, "status = 'cancelled'")}
      ${edit("return", 1, "actual_return_at = '2026-01-05 10:00:00+00'")}
      ${move("c", 10, "2026-01-01", "paid")}
      ${edit("paid", 1, "daily_rate = 95")}`);

    expect(get(rows, "pending")).toEqual(["ok"]);
    expect(get(rows, "rate")).toEqual(["ST007"]);
    expect(get(rows, "status")).toEqual(["ST007"]);
    expect(get(rows, "return")).toEqual(["ST007"]);
    expect(get(rows, "paid")).toEqual(["ST007"]);
  });

  it("should not lock a booking of another month, of another partner, or of a draft settlement (AC02)", () => {
    const rows = run(`
      ${setup(11)} ${setup(12)}
      ${rental(1, 11, 1)} ${rental(2, 11, 2)} ${rental(3, 12, 1)}
      ${asUser("admin")}
      ${generate(11, "2026-01-01")}
      ${move("a", 11, "2026-01-01", "pending_approval")}
      ${move("b", 11, "2026-01-01", "approved")}
      ${edit("other_month", 2, "daily_rate = 80")}
      ${edit("other_partner", 3, "daily_rate = 80")}
      ${edit("locked", 1, "daily_rate = 80")}`);

    expect(get(rows, "other_month")).toEqual(["ok"]);
    expect(get(rows, "other_partner")).toEqual(["ok"]);
    expect(get(rows, "locked")).toEqual(["ST007"]);
  });

  it("should not lock a booking whose month has no settlement yet (AC02)", () => {
    const rows = run(`
      ${setup(13)} ${rental(1, 13, 1)}
      ${edit("free", 1, "daily_rate = 80")}`);

    expect(get(rows, "free")).toEqual(["ok"]);
  });
});

describe.skipIf(!available)("adjustments after approval (VI-F04-S13, spec R19, E8)", () => {
  /** January approved, then a refund of 100 on its booking; reports the booking and the settlement. */
  const afterApproval = (partner: number, amount = "100") => `
    ${january(partner)}
    ${move("a", partner, "2026-01-01", "pending_approval")}
    ${move("b", partner, "2026-01-01", "approved")}
    ${asUser("operations_manager")}
    ${adjust("adj", 1, "'partial_refund'", amount, "'Refund after approval'")}
    ${asUser("admin")}
    do $$ declare b record; c integer; begin
      select * into b from public.bookings where id = '${bookingId(1)}';
      select count(*) into c from public.booking_adjustments where booking_id = b.id and after_settlement;
      raise notice 'R|booking|%|%|%|%', b.gross_revenue, b.partner_share, b.adjustments_total, c;
    end $$;
    ${state("jan", partner, "2026-01-01")}`;

  it("should record the adjustment but change neither the booking nor the approved settlement (AC03)", () => {
    const rows = run(afterApproval(20));

    expect(get(rows, "adj")).toEqual(["ok"]);
    expect(get(rows, "booking")).toEqual(["450.00", "135.00", "0.00", "1"]);
    expect(get(rows, "jan").slice(0, 8)).toEqual(["approved", "t", "450.00", "135.00", "315.00", "0.00", "0.00", "0.00"]);
  });

  it("should apply it in the next settlement: less gross, less partner share, shown as a refund (AC03)", () => {
    const rows = run(`
      ${afterApproval(21)}
      ${rental(2, 21, 2)}
      ${generate(21, "2026-02-01")}
      ${state("feb", 21, "2026-02-01")}
      ${state("jan_again", 21, "2026-01-01")}`);

    // February earns 450.00 (135.00 to the partner); 100.00 refunded on January takes 30.00 of the
    // partner share (the 30 percent the booking kept).
    expect(get(rows, "feb")).toEqual(["draft", "t", "350.00", "105.00", "245.00", "100.00", "0.00", "0.00", "105.00"]);
    expect(get(rows, "jan_again").slice(0, 3)).toEqual(["approved", "t", "450.00"]);
  });

  it("should show a chargeback and a manual adjustment under their own columns", () => {
    const rows = run(`
      ${january(22)}
      ${move("a", 22, "2026-01-01", "pending_approval")}
      ${move("b", 22, "2026-01-01", "approved")}
      ${asUser("operations_manager")}
      ${adjust("c", 1, "'chargeback'", "40", "'Bank'")}
      ${adjust("m", 1, "'manual_adjustment'", "10", "'Fix'")}
      ${asUser("admin")}
      ${rental(2, 22, 2)}
      ${generate(22, "2026-02-01")}
      ${state("feb", 22, "2026-02-01")}`);

    expect(get(rows, "feb")).toEqual(["draft", "t", "400.00", "120.00", "280.00", "0.00", "10.00", "40.00", "120.00"]);
  });

  it("should take an adjustment once: the settlement after the next one does not take it again", () => {
    const rows = run(`
      ${afterApproval(23)}
      ${rental(2, 23, 2)} ${rental(3, 23, 3)}
      ${generate(23, "2026-02-01")}
      ${generate(23, "2026-03-01")}
      ${state("mar", 23, "2026-03-01")}
      do $$ begin raise notice 'R|links|%', (select count(*) from public.settlement_carried_adjustments); end $$;`);

    expect(get(rows, "mar").slice(0, 3)).toEqual(["draft", "t", "450.00"]);
    expect(get(rows, "links")).toEqual(["1"]);
  });

  it("should make a settlement for a month that has only such an adjustment, with a negative gross revenue", () => {
    const rows = run(`
      ${afterApproval(24)}
      ${generate(24, "2026-02-01")}
      ${state("feb", 24, "2026-02-01")}`);

    expect(get(rows, "feb")).toEqual(["draft", "t", "-100.00", "-30.00", "-70.00", "100.00", "0.00", "0.00", "-30.00"]);
  });

  it("should still refuse a month with no rental and nothing carried (ST004)", () => {
    const rows = run(`
      ${january(25)}
      ${asUser("admin")}
      ${attempt("feb", `perform public.generate_monthly_settlement('${partnerId(25)}', date '2026-02-01');`)}`);

    expect(get(rows, "feb")).toEqual(["ST004"]);
  });

  it("should not let carried adjustments of one booking add up to more than its gross revenue (BA003)", () => {
    const rows = run(`
      ${afterApproval(27, "400")}
      ${asUser("operations_manager")}
      ${adjust("more", 1, "'partial_refund'", "50.01", "'Too much'")}
      ${adjust("rest", 1, "'partial_refund'", "50", "'The rest'")}`);

    expect(get(rows, "more")).toEqual(["BA003"]);
    expect(get(rows, "rest")).toEqual(["ok"]);
  });

  it("should still recalculate the booking at once when its settlement is not approved", () => {
    const rows = run(`
      ${january(28)}
      ${move("a", 28, "2026-01-01", "pending_approval")}
      ${asUser("operations_manager")}
      ${adjust("adj", 1, "'partial_refund'", "100", "'x'")}
      do $$ declare b record; begin
        select * into b from public.bookings where id = '${bookingId(1)}';
        raise notice 'R|booking|%|%', b.gross_revenue, b.adjustments_total;
      end $$;`);

    expect(get(rows, "booking")).toEqual(["350.00", "-100.00"]);
  });
});
